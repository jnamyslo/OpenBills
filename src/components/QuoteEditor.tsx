import React, { useState, useEffect } from 'react';
import logger from '../utils/logger';
import { mergeAttachmentContent, quoteNeedsContent } from '../utils/attachmentContent';
import { apiService } from '../services/api';
import { Save } from 'lucide-react';
import { arrayMove } from '@dnd-kit/sortable';
import { useQuotes } from '../context/QuoteContext';
import { useCustomers } from '../context/CustomerContext';
import { useCompany } from '../context/CompanyContext';
import { DocumentChain } from './DocumentChain';
import { useDocumentHelpers } from '../hooks/useDocumentHelpers';
import { Quote, QuoteItem, QuoteAttachment } from '../types';
import { AttachmentManager } from './AttachmentManager';
import { calculateInvoiceWithDiscounts, updateItemWithDiscount, validateDiscount } from '../utils/discountUtils';
import { DocumentPreview, PreviewDocument } from './DocumentPreview';
import { RatesAndMaterialsRedirectModal } from './RatesAndMaterialsRedirectModal';
import { CustomerCreateModal } from './CustomerCreateModal';
import { PageShell } from './PageShell';
import { QuoteCustomerResponsePanel } from './QuoteCustomerResponse';
import { generateUUID } from '../utils/uuid';
import { LineItemList } from './LineItemList';
import { FormSection, CustomerPicker, TemplateAddBar, GlobalDiscountSection, DocumentTotals, fieldInputClass, fieldLabelClass } from './DocumentFormParts';

interface QuoteEditorProps {
  quote?: Quote | null;
  onClose: () => void;
  onNavigateToCustomers?: () => void;
  onNavigateToSettings?: () => void;
}

export function QuoteEditor({ quote, onClose, onNavigateToCustomers, onNavigateToSettings }: QuoteEditorProps) {
  const { customers } = useCustomers();
  const { company } = useCompany();
  const { addQuote, updateQuote } = useQuotes();
  const { getMaterialTemplatesForCustomer, getHourlyRatesForCustomer, getCombinedMaterialTemplatesForCustomer, getCombinedHourlyRatesForCustomer } = useDocumentHelpers();
  const discountsEnabled = company.discountsEnabled !== false;

  const [quoteNumber, setQuoteNumber] = useState('');
  const [selectedCustomerId, setSelectedCustomerId] = useState('');
  const [issueDate, setIssueDate] = useState('');
  const [validUntil, setValidUntil] = useState('');
  const [items, setItems] = useState<QuoteItem[]>([]);
  const [notes, setNotes] = useState('');
  const [globalDiscountType, setGlobalDiscountType] = useState<'percentage' | 'fixed' | undefined>(undefined);
  const [globalDiscountValue, setGlobalDiscountValue] = useState<number | undefined>(undefined);
  const [attachments, setAttachments] = useState<QuoteAttachment[]>([]);
  const [showCustomerForm, setShowCustomerForm] = useState(false);
  const [previewDocuments, setPreviewDocuments] = useState<PreviewDocument[]>([]);
  const [showPreview, setShowPreview] = useState(false);
  const [showRatesRedirectModal, setShowRatesRedirectModal] = useState(false);
  const [isSubmitting, setIsSubmitting] = useState(false);

  // Calculate valid until date (30 days by default)
  function calculateValidUntil(issueDate: string) {
    const date = new Date(issueDate);
    date.setDate(date.getDate() + 30);
    return date.toISOString().split('T')[0];
  }

  function createEmptyItem(order: number): QuoteItem {
    return {
      id: generateUUID(),
      description: '',
      quantity: 1,
      unitPrice: 0,
      taxRate: company.isSmallBusiness ? 0 : 19,
      total: 0,
      order: order,
      discountType: undefined,
      discountValue: undefined,
      discountAmount: 0
    };
  }

  // Initialize form
  useEffect(() => {
    if (quote) {
      // Edit mode
      setQuoteNumber(quote.quoteNumber);
      setSelectedCustomerId(quote.customerId);
      setIssueDate(new Date(quote.issueDate).toISOString().split('T')[0]);
      setValidUntil(new Date(quote.validUntil).toISOString().split('T')[0]);
      setItems(quote.items || []);
      setNotes(quote.notes || '');
      setGlobalDiscountType(quote.globalDiscountType);
      setGlobalDiscountValue(quote.globalDiscountValue);
      setAttachments(quote.attachments || []);
    } else {
      // Create mode - leave quote number empty, it will be generated by the backend
      const today = new Date().toISOString().split('T')[0];
      setIssueDate(today);
      setValidUntil(calculateValidUntil(today));
      setQuoteNumber('');
      setItems([]);
    }
    // Intentionally keyed on `quote` only: a changing `customers` reference
    // (background refresh, add/edit elsewhere) must NOT reset an in-progress form.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [quote]);

  // Listen liefern Anhänge ohne Inhalt: für Vorschau/Download nachladen.
  useEffect(() => {
    if (!quote || !quoteNeedsContent(quote)) return;
    let cancelled = false;
    apiService.getQuote(quote.id)
      .then(full => {
        if (!cancelled) setAttachments(prev => mergeAttachmentContent(prev, full.attachments || []));
      })
      .catch(error => logger.error('Fehler beim Laden der Anhänge:', error));
    return () => { cancelled = true; };
  }, [quote]);

  const nextOrder = (list: QuoteItem[]) =>
    list.length > 0 ? Math.max(...list.map(i => i.order || 0)) + 1 : 1;

  const addItem = () => {
    setItems(prev => [...prev, createEmptyItem(nextOrder(prev))]);
  };

  // Get templates based on dropdown mode
  const materialTemplates = company.showCombinedDropdowns
    ? getCombinedMaterialTemplatesForCustomer(selectedCustomerId)
    : getMaterialTemplatesForCustomer(selectedCustomerId);

  const hourlyRateTemplates = company.showCombinedDropdowns
    ? getCombinedHourlyRatesForCustomer(selectedCustomerId)
    : getHourlyRatesForCustomer(selectedCustomerId);

  const templateName = (template: { name: string }) =>
    (('displayName' in template ? template.displayName : undefined) as string | undefined) || template.name;

  const addItemFromTemplate = (templateType: 'material' | 'hourly', templateId: string) => {
    if (templateType === 'material') {
      const template = materialTemplates.find(t => t.id === templateId);
      if (!template) return;
      setItems(prev => [...prev, {
        id: generateUUID(),
        description: template.name,
        kind: 'material',
        quantity: 1,
        unitPrice: template.unitPrice,
        taxRate: company.isSmallBusiness ? 0 : (template.taxRate != null ? template.taxRate : 19),
        total: template.unitPrice,
        order: nextOrder(prev),
        discountType: undefined,
        discountValue: undefined,
        discountAmount: 0
      }]);
    } else {
      const template = hourlyRateTemplates.find(t => t.id === templateId);
      if (!template) return;
      setItems(prev => [...prev, {
        id: generateUUID(),
        description: template.name + (template.description ? ` - ${template.description}` : ''),
        kind: 'labor',
        hourlyRateId: template.id,
        quantity: 1,
        unitPrice: template.rate,
        taxRate: company.isSmallBusiness ? 0 : (template.taxRate != null ? template.taxRate : 19),
        total: template.rate,
        order: nextOrder(prev),
        discountType: undefined,
        discountValue: undefined,
        discountAmount: 0
      }]);
    }
  };

  const updateItem = (id: string, field: keyof QuoteItem, value: string | number | undefined) => {
    setItems(prev => prev.map(item => {
      if (item.id !== id) return item;
      const updated = { ...item, [field]: value };
      // Bei Kleinunternehmerregelung immer MwSt. auf 0 setzen
      if (company.isSmallBusiness && field === 'taxRate') {
        updated.taxRate = 0;
      }
      if (field === 'quantity' || field === 'unitPrice' || field === 'taxRate' ||
          field === 'discountType' || field === 'discountValue') {
        return { ...updated, ...updateItemWithDiscount(updated) };
      }
      return updated;
    }));
  };

  const removeItem = (id: string) => {
    setItems(prev => prev.filter(item => item.id !== id));
  };

  const reorderItems = (fromIndex: number, toIndex: number) => {
    setItems(prev => arrayMove(prev, fromIndex, toIndex).map((item, i) => ({ ...item, order: i + 1 })));
  };

  const calculateTotals = () => {
    return calculateInvoiceWithDiscounts(
      items,
      { type: globalDiscountType, value: globalDiscountValue },
      company?.isSmallBusiness
    );
  };

  const handlePreview = (attachments: (QuoteAttachment)[]) => {
    const docs: PreviewDocument[] = attachments.map((att) => ({
      id: att.id,
      name: att.name,
      type: 'attachment' as const,
      size: att.size,
      content: att.content,
      contentType: att.contentType
    }));

    setPreviewDocuments(docs);
    setShowPreview(true);
  };

  const handleClosePreview = () => {
    setShowPreview(false);
    setPreviewDocuments([]);
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();

    if (!selectedCustomerId) {
      alert('Bitte wählen Sie einen Kunden aus');
      return;
    }

    if (items.length === 0) {
      alert('Bitte fügen Sie mindestens eine Position hinzu');
      return;
    }

    // Validate all items
    for (const item of items) {
      if (!item.description || item.quantity <= 0 || item.unitPrice < 0) {
        alert('Bitte füllen Sie alle Pflichtfelder korrekt aus');
        return;
      }
    }

    // Validate global discount if present
    if (globalDiscountType && globalDiscountValue) {
      const validation = validateDiscount(
        globalDiscountType,
        globalDiscountValue,
        calculateTotals().subtotal
      );

      if (!validation.isValid) {
        alert(validation.error);
        return;
      }
    }

    setIsSubmitting(true);

    const totals = calculateTotals();
    const customer = customers.find(c => c.id === selectedCustomerId);
    // Bei Kleinunternehmerregelung MwSt. auch in den gespeicherten Positionen auf 0 normalisieren
    const itemsToSave = items.map(item => ({
      ...item,
      taxRate: company.isSmallBusiness ? 0 : item.taxRate,
      total: (item.quantity * item.unitPrice) - (item.discountAmount || 0)
    }));

    const quoteData: Omit<Quote, 'id' | 'createdAt'> = {
      quoteNumber: quote ? quoteNumber : '', // Keep existing number for updates, empty for new quotes
      customerId: selectedCustomerId,
      customerName: customer?.name || '',
      issueDate: new Date(issueDate),
      validUntil: new Date(validUntil),
      items: itemsToSave,
      subtotal: totals.subtotal,
      taxAmount: totals.taxAmount,
      total: totals.total,
      status: quote?.status || 'draft',
      notes,
      globalDiscountType,
      globalDiscountValue,
      globalDiscountAmount: totals.globalDiscountAmount,
      attachments
    };

    try {
      if (quote) {
        await updateQuote(quote.id, quoteData);
        logger.info('Angebot aktualisiert', { quoteNumber });
      } else {
        await addQuote(quoteData);
        logger.info('Angebot erstellt', { quoteNumber });
      }
      onClose();
    } catch (error) {
      logger.error('Fehler beim Speichern des Angebots', { error });
      alert('Fehler beim Speichern des Angebots');
    } finally {
      setIsSubmitting(false);
    }
  };

  const totals = calculateTotals();

  return (
    <div>
      <PageShell
        title={quote ? 'Angebot bearbeiten' : 'Neues Angebot'}
        subtitle={quote ? quote.quoteNumber : 'Erstellen Sie ein neues Angebot'}
        onClose={onClose}
        header={quote ? <DocumentChain kind="quote" id={quote.id} /> : undefined}
        footer={
          <>
            <button
              type="button"
              onClick={onClose}
              disabled={isSubmitting}
              className="px-6 py-2 border border-gray-300 rounded-lg text-gray-700 hover:bg-gray-50 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
            >
              Abbrechen
            </button>
            <button
              type="submit"
              form="quote-form"
              disabled={isSubmitting}
              className="px-6 py-2 btn-primary rounded-lg transition-colors flex items-center justify-center space-x-2 disabled:opacity-50 disabled:cursor-not-allowed"
            >
              <Save className="h-4 w-4" />
              <span>{isSubmitting ? 'Wird gespeichert...' : (quote ? 'Aktualisieren' : 'Erstellen')}</span>
            </button>
          </>
        }
      >
        <form id="quote-form" onSubmit={handleSubmit} className="space-y-6">

          <QuoteCustomerResponsePanel response={quote?.customerResponse} />

          <FormSection title="Grundinformationen">
            <div className="grid grid-cols-1 gap-4">
              <div>
                <label className={fieldLabelClass}>
                  Angebotsnummer
                </label>
                <input
                  type="text"
                  value={quoteNumber}
                  placeholder={quote ? "" : "Wird automatisch generiert"}
                  disabled={true}
                  readOnly={true}
                  className="w-full px-3 py-2 border border-gray-300 rounded-lg bg-gray-100 text-gray-500 cursor-not-allowed"
                />
                <p className="text-xs text-gray-500 mt-1">
                  {quote ? "Angebotsnummern können nach der Erstellung nicht mehr geändert werden" : "Die Angebotsnummer wird beim Speichern automatisch generiert (Format: AN-YYYY-XXX)"}
                </p>
              </div>

              <CustomerPicker
                customers={customers}
                selectedId={selectedCustomerId}
                onSelect={(c) => setSelectedCustomerId(c?.id || '')}
                onCreateNew={() => setShowCustomerForm(true)}
              />

              <div>
                <label className={fieldLabelClass}>
                  Angebotsdatum *
                </label>
                <input
                  type="date"
                  required
                  value={issueDate}
                  onChange={(e) => {
                    setIssueDate(e.target.value);
                    setValidUntil(calculateValidUntil(e.target.value));
                  }}
                  className={fieldInputClass}
                />
              </div>

              <div>
                <label className={fieldLabelClass}>
                  Gültig bis *
                </label>
                <input
                  type="date"
                  required
                  value={validUntil}
                  onChange={(e) => setValidUntil(e.target.value)}
                  className={fieldInputClass}
                />
                <p className="text-xs text-gray-500 mt-1">
                  Wird automatisch auf 30 Tage nach Angebotsdatum gesetzt.
                </p>
              </div>
            </div>
          </FormSection>

          <FormSection title="Positionen">
            <TemplateAddBar
              groups={[
                {
                  label: 'Stundensätze',
                  options: hourlyRateTemplates.map(template => ({
                    value: `hourly:${template.id}`,
                    label: `${templateName(template)} - ${(Number(template.rate) || 0).toFixed(2)}€/h`,
                  })),
                },
                {
                  label: 'Materialien',
                  options: materialTemplates.map(template => ({
                    value: `material:${template.id}`,
                    label: `${templateName(template)} - ${(Number(template.unitPrice) || 0).toFixed(2)}€/${template.unit}`,
                  })),
                },
              ]}
              onSelect={(value) => {
                const [templateType, templateId] = value.split(':');
                addItemFromTemplate(templateType as 'material' | 'hourly', templateId);
              }}
              onManage={() => setShowRatesRedirectModal(true)}
              onAddManual={addItem}
            />
            <LineItemList
              items={items}
              onUpdate={updateItem}
              onRemove={removeItem}
              onReorder={reorderItems}
              isSmallBusiness={company.isSmallBusiness || false}
              discountsEnabled={discountsEnabled}
            />
          </FormSection>

          {items.length > 0 && discountsEnabled && (
            <GlobalDiscountSection
              type={globalDiscountType}
              value={globalDiscountValue}
              amount={totals.globalDiscountAmount}
              onChange={({ type, value }) => {
                setGlobalDiscountType(type);
                setGlobalDiscountValue(value);
              }}
            />
          )}

          {items.length > 0 && (
            <DocumentTotals
              totals={totals}
              discountsEnabled={discountsEnabled}
              isSmallBusiness={company.isSmallBusiness || false}
            />
          )}

          <FormSection title="Notizen">
            <textarea
              value={notes}
              onChange={(e) => setNotes(e.target.value)}
              rows={4}
              className={`${fieldInputClass} resize-none`}
              placeholder="Optional: Zusätzliche Informationen für das Angebot..."
            />
          </FormSection>

          <FormSection title="Anhänge">
            <AttachmentManager
              attachments={attachments}
              onAttachmentsChange={setAttachments}
              allowUpload={true}
              allowPreview={true}
              onPreview={handlePreview}
            />
          </FormSection>
        </form>
      </PageShell>

      {/* Document Preview Modal */}
      {showPreview && (
        <DocumentPreview
          isOpen={showPreview}
          onClose={handleClosePreview}
          documents={previewDocuments}
          initialIndex={0}
        />
      )}

      {showCustomerForm && (
        <CustomerCreateModal
          onClose={() => setShowCustomerForm(false)}
          onCreated={(c) => setSelectedCustomerId(c.id)}
        />
      )}

      <RatesAndMaterialsRedirectModal
        isOpen={showRatesRedirectModal}
        onClose={() => setShowRatesRedirectModal(false)}
        onNavigateToCustomers={() => onNavigateToCustomers && onNavigateToCustomers()}
        onNavigateToSettings={() => onNavigateToSettings && onNavigateToSettings()}
        type="materials"
      />
    </div>
  );
}
